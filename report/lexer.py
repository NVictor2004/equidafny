OPERATORS = ('..', '::', ':=', '!', '=', '|', '=>', '<==>', '<==', '==>', '&&', '||', '==', '!=', '<', '<=', '>', '>=', '+', '-', '*', '/', '%')

class CustomLexer(RegexLexer):
    name = 'Dafny'
    filenames = ['*.dfy']

    tokens = {
        'root': [
            (r"\s+", Whitespace),
            (r"//.*?$", Comment.Single),
            (words(KEYWORDS, suffix=r'\b'), Keyword),
            (words(OPERATORS), Operator),
            (r"\d+", Number),
            (r"\"[^\"]*\"", String),
            (r"\b([A-Za-z_?\'][A-Za-z0-9_?\']*)(\()", bygroups(Name.Function, Punctuation)),
            (r"\b([A-Za-z_?\'][A-Za-z0-9_?\']*)(\<)", bygroups(Name.Function, Punctuation), "type_list"),
            (r"(:)(?!=)", Punctuation, "single_type"),
            (r"\b[A-Za-z_?\'][A-Za-z0-9_?\']*\b", Name),
            (r"[\(\)\[\]\{\},;]", Punctuation),
        ],
        'type_list': [
            (r"\s+", Whitespace),
            (r"\b[A-Za-z_?\'][A-Za-z0-9_?\']*\b", Keyword.Type),
            (r",", Punctuation),
            (r"[<\(]", Punctuation, "#push"),
            (r"[>\)]", Punctuation, "#pop"),
        ],
        'single_type': [
            (r"\n", Whitespace, "#pop"),
            (r"[,\)\{;]", Punctuation, "#pop"),
            (r"::", Operator, "#pop"),
            (r"\s+", Whitespace),
            (r"->", Operator),
            (r"\b[A-Za-z_?\'][A-Za-z0-9_?\']*\b", Keyword.Type),
            (r"[<\(]", Punctuation, "type_list"),
        ]
    }
